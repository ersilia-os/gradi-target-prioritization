"""Shared helpers for the degradability assessment stage (docs §3, scripts/10*).

Deliberately thin, in the same spirit as `src/essentiality.py`: it **reuses** the ligandability
helpers (`src/ligandability.py`) for the generic machinery — organism config, proteome loading, the
03a ortholog table, DIAMOND, output paths — and the essentiality helpers for the E. coli -> Kp
ortholog transfer. On top of that it adds only what is degradability-specific:

  * `terminal_plddt()` / `init_region_len()` / `exposure()` — the structural half of docs §3.1a/§3.1b.
    The spec's central idea (down-weight a degron motif when the terminus sits in a folded,
    high-pLDDT region) was never implemented by the legacy prototype; this is it. We read the
    AlphaFold models from the **existing** `data/processed/<org>/pockets/pdb/<ACC>.pdb` cache written
    by 06e (B-factor == pLDDT), rather than re-parsing the mmCIFs.
  * corrected degron motif definitions (see the MOTIFS table below for why each legacy regex changed),
    each with the published archetype it must match — asserted by `selftest_motifs()`.
  * `growth_corrected_kdeg()` — pulsed-SILAC half-lives conflate proteolysis with growth dilution.
  * the per-paper Clp-trap weights and the auditable scoring constants used by the 10h merge.

Keying is always by UniProt accession (project convention). Run with the `gradi` conda env.

Why the legacy motif set was replaced rather than tuned
-------------------------------------------------------
The deleted prototype (`git show 8327de3^:scripts/03_annotate_clp_degradability.py`) had three
defects that a weight change cannot fix:

1. **The N-end rule feature was inverted.** Met-aminopeptidase excises the initiator Met only when
   residue 2 has a small side chain (A,C,G,P,S,T,V; Hirel 1989). When residue 2 is L/F/Y/W the iMet
   is *retained*, and Met is a *stabilizing* N-terminal residue in E. coli — so `pos2 in LFYW`
   selects precisely the proteins that cannot expose an N-degron by iMet cleavage. It fired on 684
   Kp proteins at +0.25 each and single-handedly produced 680 of the 698 "medium" calls. Measured
   enrichment for fast turnover against the real Nagar 2021 classes: 1.30x, i.e. noise. Bacterial
   N-degrons are physiologically generated by endoproteolysis or by Aat-mediated Leu/Phe transfer
   (Erbse 2006, Ninnis 2009), which cannot be predicted from the primary sequence. We therefore emit
   `nend_primary_destabilizing` AND `nend_imet_cleaved` as provenance columns and weight both 0.
2. **The CM1 regex did not match its own archetype.** `[YAFWLIVM]?[ALV]A[ALV]A$` fails on the ssrA
   tag `AANDENYALAA`. Its 5 proteome-wide "hits" (AAALA, KLAVA, TAAAA, PLALA, RLALA) are unrelated
   to ssrA. Replaced, and `selftest_motifs()` now asserts the archetype match.
3. **CM2/MuA carries no signal** in the only labelled data we have (0 fast-degraders among 28 hits).
   Kept as a column for transparency, weight 0.

Consequently the weighting shifts decisively away from sequence motifs and onto terminal structural
exposure (the one dense, correctly-signed, full-coverage feature) plus experimental evidence.
"""

