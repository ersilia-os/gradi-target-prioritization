def halflife_evidence(halflife_class: str | None, trapped: bool = False) -> float | None:
    """Map a turnover class (+ trap corroboration) to a [0,1] Clp-substrate evidence sub-score.

    Rapid turnover alone is weak, protease-ambiguous evidence: Lon recognises exposed hydrophobic
    patches without an adaptor and accounts for a large share of fast turnover in E. coli
    (Gur & Sauer 2008; the caveat docs §3 raises via Olivares/Sauer). So `fast` corroborated by a
    Clp trap scores near the top, while `fast` alone is capped mid-scale. Unmeasured returns None so
    the weight is renormalised away rather than read as "measured stable".
    """
    c = (halflife_class or "").strip().lower()
    if trapped:
        return 1.0 if c == "fast" else 0.90
    if c == "fast":
        return 0.55
    if c == "intermediate":
        return 0.35
    if c == "stable":
        return 0.0
    return None


def trap_evidence(papers: list[str] | None) -> tuple[float | None, bool]:
    """Pooled, per-paper-weighted trap evidence and a ClpC-only flag.

    Returns (score, clpc_only). `score` is the maximum per-paper weight (evidence does not compound
    — two traps in the same organism are not twice the proof), capped at CLPC_ONLY_CAP when every
    supporting paper used a ClpC-family protease that neither focal organism encodes.
    """
    keys = [p for p in (papers or []) if p in TRAP_PAPERS]
    if not keys:
        return None, False
    clpc_only = all(TRAP_PAPERS[k]["protease"] in CLPC_LIKE for k in keys)
    score = max(TRAP_PAPERS[k]["weight"] for k in keys)
    if clpc_only:
        score = min(score, CLPC_ONLY_CAP)
    return round(float(score), 4), clpc_only


def renormalised_score(parts: dict[str, float | None],
                       weights: dict[str, float]) -> tuple[float | None, float]:
    """Weighted mean over the AVAILABLE parts, plus the retained weight mass (the confidence).

    Same contract as the 07h composite: a part that is None is dropped and the remaining weights are
    renormalised, so a missing track lowers confidence rather than pushing the score toward zero.
    Returns (score, confidence); score is None when nothing is available.
    """
    num = 0.0
    den = 0.0
    for key, w in weights.items():
        v = parts.get(key)
        if v is None or pd.isna(v):
            continue
        num += float(w) * float(v)
        den += float(w)
    if den <= 0:
        return None, 0.0
    total = sum(weights.values())
    return round(num / den, 4), round(den / total, 4)


def degradability_tier(score: float | None, confidence: float,
                       hard_evidence: bool = False) -> str:
    """Evidence-driven tier: high / medium / low / insufficient_evidence.

    `insufficient_evidence` is a first-class state, distinct from `low`. The legacy axis reported all
    4,675 no-ortholog Kp proteins as `low`, indistinguishable in the browser from a protein measured
    to be stable. A `high` call requires a hard evidence source (own or ortholog Clp trap, or fast
    turnover corroborated by a trap) or a score that clears TIER_HIGH *with* enough retained weight
    mass — never the degron prior alone.
    """
    if score is None or confidence <= 0:
        return "insufficient_evidence"
    if hard_evidence or (score >= TIER_HIGH and confidence >= MIN_CONFIDENCE_FOR_HIGH):
        return "high"
    if score >= TIER_MEDIUM:
        return "medium"
    return "low"


