# --------------------------------------------------------------------------- scoring (10h)
# All weights/thresholds are module-level so the composite is auditable and tunable, exactly as
# src/essentiality.py is consumed by 07h. A sub-score that is entirely absent for a protein is
# DROPPED and the remaining weights renormalised in 10h — never zero-filled.
