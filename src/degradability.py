def match_motif(name: str, sequence: str) -> bool:
    """True if `sequence` carries motif `name`. C-terminal motifs are anchored at the C-terminus."""
    spec = MOTIFS[name]
    return bool(spec["rx"].search(sequence.upper()))


def selftest_motifs() -> None:
    """Assert every motif matches the published archetype it claims to encode.

    This is the five-line test whose absence let a CM1 regex that cannot match the ssrA tag ship to
    the browser. Called at the top of 10b so the pipeline cannot run with a broken motif.
    """
    for name, spec in MOTIFS.items():
        for key in ("archetype", "archetype2"):
            arch = spec.get(key)
            if not arch:
                continue
            assert match_motif(name, arch), (
                f"motif {name} fails its {key} {arch!r} — pattern {spec['rx'].pattern!r}"
            )
    # Negative controls: the ssrA tag is not basic-aliphatic, and MuA does not end in -AA.
    assert not match_motif("cterm_cm2", "AANDENYALAA")
    assert not match_motif("cterm_cm1_strict", "GSGMSRRKKAI")
    # N-motif cross-controls: Flynn assigns these to N-M1 and N-M3 respectively, so each must NOT
    # match the other's pattern, or the two features are not separating what they claim to.
    assert not match_motif("nterm_nm3", MOTIFS["nterm_nm1"]["archetype"]), "Dps should not hit NM3"
    assert not match_motif("nterm_nm1", MOTIFS["nterm_nm3"]["archetype"]), "Crl should not hit NM1"
    # And Flynn's N-M2 proteins (DadA, OmpA) belong to neither.
    for nm2_seq in ("MRVVILGSGVVGV", "MKKTAIAIAVALA"):
        assert not match_motif("nterm_nm1", nm2_seq)
        assert not match_motif("nterm_nm3", nm2_seq)


# --------------------------------------------------------------------------- half-life handling
# Nagar 2021 pulsed-SILAC growth condition. Half-lives from a growing culture conflate proteolysis
# with dilution by division, and for this axis only the proteolytic part is evidence: a 34-minute
# apparent half-life in a ~40-minute doubling culture corresponds to a *proteolytic* half-life of
# ~230 minutes. Verified against the paper in docs/degradability_references.md.
NAGAR_DOUBLING_MIN = 40.0
# Nagar's `label` / `Stability` classes, resolved by measuring the median half-life of each class
# (label 1 median 34 min; label 0 median 200 min; label 2 median 411 min with 241 infinite).
NAGAR_LABELS: dict[int, str] = {1: "fast", 0: "intermediate", 2: "stable"}


def nagar_dir() -> Path:
    return degradability_raw_dir("ecoli", "nagar2021_halflife")


def load_nagar() -> pd.DataFrame:
    """Nagar 2021 per-protein turnover, keyed by UniProt accession (E. coli K-12, native evidence).

    Reads `sd002` (1,149 proteins with the paper's own `label` + `half_life`) and enriches it with
    the `sd003` `Stability` class where present. Both sheets key on `Protein IDs`, which already
    holds UniProt accessions — no gene-symbol bridge, so this lands on the anchor proteome directly.

    Columns: uniprot_accession, halflife_min, halflife_class, kdeg_growth_corrected,
             halflife_proteolytic_min, nagar_label.

    Returns an empty frame (not an error) when the fetch has not run, so 10b/10c degrade gracefully.
    """
    cols = ["uniprot_accession", "halflife_min", "halflife_class",
            "kdeg_growth_corrected", "halflife_proteolytic_min", "nagar_label"]
    files = sorted(nagar_dir().glob("*sd002*.xlsx"))
    if not files:
        return pd.DataFrame(columns=cols)
    raw = pd.read_excel(files[0], usecols=["Protein IDs", "label", "half_life"])
    raw = raw.rename(columns={"Protein IDs": "uniprot_accession", "label": "nagar_label",
                              "half_life": "halflife_min"})
    # `Protein IDs` can carry a MaxQuant multi-protein group (`P0A9Q7;P12345`); the first id is the
    # leading/representative protein for the group.
    raw["uniprot_accession"] = (raw["uniprot_accession"].astype(str).str.split(";").str[0].str.strip())
    raw["halflife_min"] = pd.to_numeric(raw["halflife_min"], errors="coerce")
    raw["halflife_class"] = raw["nagar_label"].map(NAGAR_LABELS).fillna("unknown")
    raw["kdeg_growth_corrected"] = raw["halflife_min"].map(growth_corrected_kdeg)
    raw["halflife_proteolytic_min"] = raw["halflife_min"].map(proteolytic_half_life)
    out = raw.drop_duplicates("uniprot_accession")[cols].reset_index(drop=True)
    return out


def growth_corrected_kdeg(t_half_min: float | None,
                          doubling_min: float = NAGAR_DOUBLING_MIN) -> float | None:
    """Proteolytic degradation rate constant (min^-1) from an apparent half-life.

    k_deg = ln2/t_half - mu, with mu = ln2/doubling_min. Clamped at 0: an apparent half-life at or
    above the doubling time means dilution explains the whole signal, i.e. no evidence of
    proteolysis. Returns None for missing/non-positive/infinite input.
    """
    if t_half_min is None or pd.isna(t_half_min):
        return None
    try:
        t = float(t_half_min)
    except (TypeError, ValueError):
        return None
    if t <= 0 or math.isinf(t):
        return None
    mu = math.log(2.0) / float(doubling_min)
    return round(max(0.0, math.log(2.0) / t - mu), 6)


def proteolytic_half_life(t_half_min: float | None,
                          doubling_min: float = NAGAR_DOUBLING_MIN) -> float | None:
    """Growth-corrected half-life in minutes (None when dilution explains the whole decay)."""
    k = growth_corrected_kdeg(t_half_min, doubling_min)
    if not k:
        return None
    return round(math.log(2.0) / k, 1)


