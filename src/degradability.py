# --------------------------------------------------------------------------- structural exposure
# AlphaFold's conventional confidence break: pLDDT < 70 is "low confidence", and in monomeric
# predictions such regions are the standard proxy for intrinsic disorder. It is also the threshold
# the disorder filter in docs §2.4 uses, so degradability and ligandability stay commensurable.
PLDDT_DISORDER_CUT = 70.0
# Logistic width, in pLDDT units, of the ordered->disordered transition. 8 puts exposure at ~0.08
# for a well-folded terminus (pLDDT 90) and ~0.92 for a clearly disordered one (pLDDT 50), while
# staying smooth across the observed p10-p90 band (~54-97).
EXPOSURE_WIDTH = 8.0
# ClpXP/ClpAP need an unstructured initiation region to thread into the pore before unfolding can
# begin; the Sauer-lab estimate is roughly 10-30 residues. We report the measured length and use 15
# as the "engageable" floor for the bimodal degrader flag.
MIN_INIT_REGION = 15


def residue_plddt(pdb_path: Path) -> dict[int, float]:
    """Mean B-factor (== pLDDT) per residue number, parsed straight from the pdb.

    Same implementation as `residue_plddt` in scripts/06e_pockets.py, promoted here so both the
    pocket and the degron tracks share one parser (numpy-free so this module stays import-light).
    """
    acc: dict[int, list[float]] = {}
    with open(pdb_path) as fh:
        for line in fh:
            if line.startswith(("ATOM", "HETATM")):
                try:
                    resnum = int(line[22:26])
                    b = float(line[60:66])
                except ValueError:
                    continue
                acc.setdefault(resnum, []).append(b)
    return {r: sum(v) / len(v) for r, v in acc.items() if v}


def plddt_series(organism: str, accession: str) -> list[float]:
    """Per-residue pLDDT in residue order, or [] when no AlphaFold model is cached."""
    p = af_pdb_path(organism, accession)
    if not p.exists():
        return []
    per_res = residue_plddt(p)
    return [per_res[r] for r in sorted(per_res)]


def terminal_plddt(plddt: list[float], n: int = 10, terminus: str = "c") -> float | None:
    """Mean pLDDT over the last (`terminus="c"`) or first (`"n"`) `n` residues.

    For the N-terminus we start at residue 2, since residue 1 is the initiator Met (frequently
    excised) and its pLDDT is systematically low in AlphaFold models regardless of local order.
    """
    if not plddt:
        return None
    seg = plddt[-n:] if terminus == "c" else plddt[1:1 + n]
    if not seg:
        return None
    return round(sum(seg) / len(seg), 2)


def init_region_len(plddt: list[float], terminus: str = "c",
                    cut: float = PLDDT_DISORDER_CUT) -> int | None:
    """Length of the contiguous low-pLDDT run at a terminus — the candidate pore-initiation region.

    This is the mechanistically meaningful quantity (an unstructured segment long enough to thread),
    not the mean pLDDT: a 25-residue disordered tail on an otherwise rigid protein barely moves the
    terminal mean but is exactly what ClpXP needs.
    """
    if not plddt:
        return None
    seq = list(reversed(plddt)) if terminus == "c" else plddt[1:]
    k = 0
    for v in seq:
        if v < cut:
            k += 1
        else:
            break
    return k


def exposure(plddt: float | None, midpoint: float = PLDDT_DISORDER_CUT,
             width: float = EXPOSURE_WIDTH) -> float | None:
    """Map a terminal pLDDT to a [0,1] exposure/flexibility score (logistic, high pLDDT -> 0).

    None propagates as None so 10h can renormalise the weight away rather than scoring a protein
    with no AlphaFold model as if its terminus were buried.
    """
    if plddt is None or pd.isna(plddt):
        return None
    return round(1.0 / (1.0 + math.exp((float(plddt) - midpoint) / width)), 4)


# --------------------------------------------------------- disorder architecture (docs §3.1, 10d)
# Terminal windows the spec asks for. 10b used (10, 20); 30 matters specifically because Won 2024's
# top feature is the mean disorder of the N-terminal ~30 residues, so parity with that result needs
# a 30-residue window.
TERM_WINDOWS_SPEC = (15, 30, 50)
# Measured ClpXP initiation-region thresholds, in residues:
#   ~5  closed axial channel, 2 pore-1 loops engaged      (Saunders 2020 PNAS)
#   ~20 open axial channel, 5 pore-1 loops engaged        (Saunders 2020; Fei 2020 eLife)
#   ~37 pore-to-ClpP-active-site reach                    (Kenniston 2005 PNAS)
# Longer tails also shift the balance from futile release toward committed degradation.
INIT_THRESHOLDS = (5, 20, 37)
INIT_BUCKETS = ("none", "recognition", "engagement", "reach")
# A stricter disorder call than the pLDDT<70 confidence break, for the "clearly disordered" variant.
PLDDT_DISORDER_CUT_STRICT = 50.0
# An internal low-pLDDT stretch this long is a candidate internal degron. Degrons need not be
# terminal: internally placed ssrA tags are degraded by ClpAP/ClpXP (Hoskins 2002), and E. coli FtsZ
# carries an internal ClpXP site in its disordered linker at residues 349-358 (Camberg 2014).
MIN_INTERNAL_RUN = 10


def init_bucket(length: int | None) -> str | None:
    """Bucket an initiation-region length against the measured ClpXP thresholds."""
    if length is None or pd.isna(length):
        return None
    lo, mid, hi = INIT_THRESHOLDS
    n = int(length)
    if n >= hi:
        return "reach"
    if n >= mid:
        return "engagement"
    if n >= lo:
        return "recognition"
    return "none"


def internal_disorder_runs(plddt: list[float],
                           cut: float = PLDDT_DISORDER_CUT) -> dict[str, float | int | None]:
    """Low-pLDDT runs that touch NEITHER terminus — the internal-degron / linker case.

    Terminal runs are already `init_region_len()`; excluding them here keeps the two features
    independent, so a long disordered tail cannot masquerade as an internal linker.

    Returns max run length, run count, the fraction of residues in internal runs, and the 1-based
    start/end of the longest run (so a hit can be checked against a published site — e.g. FtsZ
    349-358).
    """
    out: dict[str, float | int | None] = {
        "internal_disorder_max_run": None, "internal_disorder_n_segments": None,
        "internal_disorder_frac": None, "internal_disorder_start": None,
        "internal_disorder_end": None,
    }
    if not plddt:
        return out
    n = len(plddt)
    runs: list[tuple[int, int]] = []   # (start_idx, end_idx) inclusive, 0-based
    i = 0
    while i < n:
        if plddt[i] < cut:
            j = i
            while j + 1 < n and plddt[j + 1] < cut:
                j += 1
            runs.append((i, j))
            i = j + 1
        else:
            i += 1
    internal = [(a, b) for a, b in runs if a > 0 and b < n - 1]
    out["internal_disorder_n_segments"] = len(internal)
    out["internal_disorder_frac"] = round(sum(b - a + 1 for a, b in internal) / n, 4)
    if internal:
        a, b = max(internal, key=lambda r: r[1] - r[0])
        out["internal_disorder_max_run"] = b - a + 1
        out["internal_disorder_start"] = a + 1      # 1-based, to compare against literature sites
        out["internal_disorder_end"] = b + 1
    else:
        out["internal_disorder_max_run"] = 0
    return out


def global_disorder_frac(plddt: list[float], cut: float = PLDDT_DISORDER_CUT) -> float | None:
    """Fraction of residues below `cut`. At cut=70 this is the same definition as the ligandability
    `disorder_frac` (06g: af_frac_low_plddt + af_frac_very_low_plddt), deliberately — the two axes
    must stay commensurable, since disorder is a *penalty* there and a *positive* here."""
    if not plddt:
        return None
    return round(sum(1 for v in plddt if v < cut) / len(plddt), 4)


# --------------------------------------------------------------------------- MobiDB
# One bulk TSV per proteome, long format: acc / feature / start..end / content_fraction /
# content_count / length. Supplies 8 independent disorder predictors plus a consensus, an
# AlphaFold-derived disorder track, Pfam/Gene3D/merged domain boundaries, LIP (linear interacting
# peptide) regions and low-complexity — at 100% of both proteomes.
#
# Why it matters beyond convenience: pLDDT-derived disorder has a known failure mode — an obligate
# complex subunit is ordered in situ but predicted disordered in isolation — so an independent
# sequence-side opinion is the guard against reading assembly context as intrinsic disorder.
MOBIDB_PREDICTORS = ("dis465", "disHL", "glo", "th_50", "espX", "iups", "espN", "iupl")


def mobidb_tsv(organism: str) -> Path | None:
    d = degradability_raw_dir(organism, "mobidb")
    files = sorted(d.glob("*_mobidb_*.tsv"))
    return files[0] if files else None


def load_mobidb(organism: str) -> pd.DataFrame:
    """Pivot the MobiDB long export to one row per accession.

    Columns: uniprot_accession, seq_len_mobidb, mobidb_dis_<predictor> (8), mobidb_disorder_priority
    (the consensus), mobidb_disorder_alphafold, mobidb_plddt_alphafold, mobidb_lip_frac,
    mobidb_low_complexity_frac, mobidb_n_domains_{pfam,gene3d,merge}, mobidb_predictor_agreement
    (how many of the 8 predictors call >10% disorder — a spread measure, not a mean).

    Returns an empty frame when the bulk file is absent, so 10d degrades to pLDDT-only rather than
    failing.
    """
    f = mobidb_tsv(organism)
    if f is None:
        return pd.DataFrame(columns=["uniprot_accession"])
    raw = pd.read_csv(f, sep="\t", usecols=["acc", "feature", "start..end", "content_fraction",
                                            "content_count", "length"])
    raw["acc"] = raw["acc"].astype(str).str.strip()

    def _frac(feature: str, name: str) -> pd.DataFrame:
        sub = raw[raw["feature"] == feature][["acc", "content_fraction"]]
        return sub.drop_duplicates("acc").rename(columns={"content_fraction": name})

    out = raw[["acc", "length"]].drop_duplicates("acc").rename(columns={"length": "seq_len_mobidb"})
    for p in MOBIDB_PREDICTORS:
        out = out.merge(_frac(f"prediction-disorder-{p}", f"mobidb_dis_{p}"), on="acc", how="left")
    for feat, name in (("prediction-disorder-priority", "mobidb_disorder_priority"),
                       ("prediction-disorder-alphafold", "mobidb_disorder_alphafold"),
                       ("prediction-plddt-alphafold", "mobidb_plddt_alphafold"),
                       ("prediction-lip-priority", "mobidb_lip_frac"),
                       ("prediction-low_complexity-seg", "mobidb_low_complexity_frac")):
        out = out.merge(_frac(feat, name), on="acc", how="left")

    # Domain counts. MobiDB emits ONE row per accession per source and packs every domain into a
    # comma-separated `start..end` ("23..143,177..229,235..295,299..452" = 4 domains), so counting
    # rows gives 1 for everything. Count the ranges instead.
    for feat, name in (("homology-domain-pfam", "mobidb_n_domains_pfam"),
                       ("homology-domain-gene3d", "mobidb_n_domains_gene3d"),
                       ("homology-domain-merge", "mobidb_n_domains_merge")):
        sub = raw[raw["feature"] == feat][["acc", "start..end"]].drop_duplicates("acc").copy()
        sub[name] = sub["start..end"].astype(str).str.count(",") + 1
        out = out.merge(sub[["acc", name]], on="acc", how="left")
    for c in ("mobidb_n_domains_pfam", "mobidb_n_domains_gene3d", "mobidb_n_domains_merge"):
        out[c] = out[c].fillna(0).astype(int)

    # MobiDB's bulk export lists only the regions a predictor FOUND. A protein the predictor judged
    # fully ordered simply has no row, so a left-join NaN means "zero disorder", not "not computed"
    # — verified: accessions with no `priority` row still carry dis465 fractions of 0.10-0.26, i.e.
    # the consensus declined to call a region rather than the predictor not having run. Treating
    # those as missing understates coverage and silently drops them from any downstream mean.
    region_fracs = ([f"mobidb_dis_{p}" for p in MOBIDB_PREDICTORS]
                    + ["mobidb_disorder_priority", "mobidb_lip_frac",
                       "mobidb_low_complexity_frac"])
    for c in region_fracs:
        if c in out.columns:
            out[c] = out[c].fillna(0.0)
    # `mobidb_plddt_alphafold` is a confidence value, not a region fraction, and
    # `mobidb_disorder_alphafold` only exists where a model does — both stay NaN when absent.

    pred_cols = [f"mobidb_dis_{p}" for p in MOBIDB_PREDICTORS]
    out["mobidb_predictor_agreement"] = (out[pred_cols] > 0.10).sum(axis=1)
    return out.rename(columns={"acc": "uniprot_accession"}).reset_index(drop=True)


# --------------------------------------------------------------------------- feature scoring
AUROC_BOOTSTRAP = 2000
AUROC_SEED = 0


def _auroc(v, y) -> float:
    """AUROC from the Mann-Whitney U statistic (no threshold, invariant to monotone rescaling)."""
    from scipy import stats
    n_pos = int(y.sum())
    n_neg = int(len(y) - n_pos)
    ranks = stats.rankdata(v)
    return float((ranks[y].sum() - n_pos * (n_pos + 1) / 2) / (n_pos * n_neg))


def disorder_auroc(values, labels, n_boot: int = AUROC_BOOTSTRAP) -> dict[str, float | int | None]:
    """Score one continuous feature against a binary label: AUROC + bootstrap CI + Spearman + n.

    AUROC answers the question that matters here — "does this feature rank fast-turnover proteins
    above stable ones" — without needing a threshold. 0.5 is the null.

    **The CI is not optional.** The labelled positive class is ~60-75 proteins, so the 95% interval on
    an AUROC is roughly +/-0.07. Reporting a bare ranking at that sample size invites reading a
    0.03 gap between two features as a real difference when it is noise. Every consumer of this
    function must plot or print `auroc_lo`/`auroc_hi` alongside the point estimate.

    Returns {auroc, auroc_lo, auroc_hi, spearman, n, n_pos}; auroc is None when either class is empty.
    """
    import numpy as np
    from scipy import stats

    v = pd.Series(values).astype(float)
    y = pd.Series(labels).astype(bool)
    ok = v.notna() & y.notna()
    v, y = v[ok].to_numpy(), y[ok].to_numpy()
    n_pos, n_neg = int(y.sum()), int((~y).sum())
    if n_pos == 0 or n_neg == 0:
        return {"auroc": None, "auroc_lo": None, "auroc_hi": None, "spearman": None,
                "n": int(len(v)), "n_pos": n_pos}

    point = _auroc(v, y)
    rho = float(stats.spearmanr(v, y.astype(int)).statistic) if len(v) > 2 else float("nan")

    lo = hi = None
    if n_boot:
        rng = np.random.default_rng(AUROC_SEED)
        pos_idx = np.flatnonzero(y)
        neg_idx = np.flatnonzero(~y)
        boots = np.empty(n_boot)
        for b in range(n_boot):
            # Stratified resample: keep the class balance fixed so the CI reflects uncertainty in the
            # ranking, not in the prevalence.
            idx = np.concatenate([rng.choice(pos_idx, n_pos, replace=True),
                                  rng.choice(neg_idx, n_neg, replace=True)])
            boots[b] = _auroc(v[idx], y[idx])
        lo, hi = (round(float(x), 4) for x in np.percentile(boots, [2.5, 97.5]))

    return {"auroc": round(point, 4), "auroc_lo": lo, "auroc_hi": hi,
            "spearman": round(rho, 4), "n": int(len(v)), "n_pos": n_pos}


# --------------------------------------------------------------------------- degron motifs
# Residue 2 identities for which Met-aminopeptidase excises the initiator Met (Hirel 1989). Used
# only to make the legacy sign error auditable — neither this nor its complement is scored.
MAP_CLEAVED = set("ACGPSTV")
# Primary destabilizing residues of the bacterial N-end rule (ClpS -> ClpAP). Scored 0: exposing one
# of these requires prior endoproteolysis or Aat transfer, which sequence alone cannot predict.
NEND_DESTABILIZING = set("LFYW")

# CM1, the ssrA/-LAA family (Flynn 2003). The archetypal ClpXP degron is the ssrA tag's C-terminus
# `...AANDENYALAA`. Two nested definitions are emitted so the reader can pick the operating point:
# `broad` (terminal -AA) and `strict` (terminal -AA preceded by a hydrophobic, i.e. the -LAA core).
CM1_BROAD_RX = re.compile(r"AA$")
CM1_STRICT_RX = re.compile(r"[LVIAFMY]AA$")
# CM2, the MuA family (Flynn 2003 archetype `-RRKKAI`): a basic patch followed by small aliphatics.
# Retained for transparency but WEIGHT 0 — it shows no enrichment in the only labelled set we have.
CM2_RX = re.compile(r"[RK]{2,}[A-Z]{0,2}[AVILMG]{1,3}$")
# NM2 (Flynn 2003): initiator Met, basic residue, then two hydrophobics.
NM2_RX = re.compile(r"^M[KR][ILVF][ILVFY]")

# NM1 and NM3 (Flynn 2003), implemented 2026-08-06 from the paper itself — see the block below for
# why the previous stand-ins were wrong and what changed.
#
# Flynn's residue classes for the N-motifs. `phi` = "hydrophobic side chain" in the paper.
NM_HYDROPHOBIC = "AILMFWVY"
NM_POLAR = "STNQCYHKRDE"      # polar incl. charged, which is how the paper's "polar" reads
NM_BASIC = "KRH"
# NM1 strict consensus: T-X-K-[ILV], "located from 1 to 4 residues from the N terminus". That phrase
# means 1-4 residues sit BEFORE the motif, not that T is at position <=4 — verified against Flynn's own
# two named archetypes: Dps `MSTAKLV` (T at position 3, so 2 residues before) and sigma-S/RpoS
# `MSQNTLKV` (T at position 5, so 4 residues before). An upper bound of 4 admits both; a "T at
# position <=4" reading would reject RpoS.
NM1_RX = re.compile(r"^.{1,4}T.K[ILV]")
# NM3 consensus: phi-X-polar-X-polar-X-basic-polar, near the N terminus. Archetypes Crl `MTLPSGHPKS`
# (matches from position 3) and DksA `MQEGQNRK` (from position 1), hence the 0-3 residue lead-in.
NM3_RX = re.compile(
    rf"^.{{0,3}}[{NM_HYDROPHOBIC}].[{NM_POLAR}].[{NM_POLAR}].[{NM_BASIC}][{NM_POLAR}]"
)

# Flynn's NM1 and NM3 ARE now implemented (above), 2026-08-06. History: the legacy `^M?[AILVMFW]{2,}` fired on
# 30.7% of the Kp proteome, and Nagar 2021's own NM1/NM3 flags (which are whole-sequence windowed
# scans, not terminal motifs) fire on 50%/74% of E. coli with no enrichment for fast turnover. A
